export type TextKey = keyof (typeof dict)['en']

export const t = (lang: Lang, key: TextKey): string => dict[lang][key] ?? dict.en[key]

/** Hindi text when the language is Hindi and a Hindi value exists, otherwise the English one. */
export const pick = (lang: Lang, en: string, hi?: string | null): string => (lang === 'hi' && hi && hi.trim() ? hi : en)

export const readLang = (
  storage: Pick<Storage, 'getItem'> | undefined = typeof localStorage === 'undefined' ? undefined : localStorage,
): Lang => {
  try {
    return storage?.getItem(LANG_KEY) === 'hi' ? 'hi' : 'en'
  } catch {
    return 'en'
  }
}
